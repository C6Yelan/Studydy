_DETAILED_REASON_CODES = FORMAL_REASON_CODES.union(
    _SOURCE_INVALID_REASONS,
    _RESOURCE_LIMIT_REASONS,
    _PROCESS_FAILED_REASONS,
    _EVIDENCE_GROUNDING_REASONS,
    _PAGE_CONTENT_UNUSABLE_REASONS,
    _MODEL_OUTPUT_INVALID_REASONS,
    _STORAGE_WRITE_REASONS,
    _CONTENT_REVIEW_REASONS,
    {
        "RUNTIME_BINDING_INVALID",
        "CHILD_TIMEOUT",
        "CONCEPT_API_CONFIG_INVALID",
        "CONCEPT_API_TIMEOUT",
        "CACHE_INVALID",
        "PRODUCER_BUNDLE_INVALID",
    },
)


def formal_reason_code(reason: str) -> str:
    if reason in FORMAL_REASON_CODES:
        return reason
    elif reason in _SOURCE_INVALID_REASONS:
        return "SOURCE_INVALID"
    elif reason in {"RUNTIME_BINDING_INVALID", "CONCEPT_API_CONFIG_INVALID"}:
        return "RUNTIME_INVALID"
    elif reason in _RESOURCE_LIMIT_REASONS:
        return "RESOURCE_LIMIT_EXCEEDED"
    elif reason in {"CHILD_TIMEOUT", "CONCEPT_API_TIMEOUT"}:
        return "PROCESS_TIMEOUT"
    elif reason in _PROCESS_FAILED_REASONS:
        return "PROCESS_FAILED"
    elif reason in _EVIDENCE_GROUNDING_REASONS:
        return "EVIDENCE_GROUNDING_INVALID"
    elif reason in _PAGE_CONTENT_UNUSABLE_REASONS:
        return "PAGE_CONTENT_UNUSABLE"
    elif reason in _MODEL_OUTPUT_INVALID_REASONS:
        return "MODEL_OUTPUT_INVALID"
    elif reason == "CACHE_INVALID":
        return "CACHE_RECOVERED"
    elif reason in _STORAGE_WRITE_REASONS:
        return "STORAGE_WRITE_FAILED"
    elif reason == "PRODUCER_BUNDLE_INVALID":
        return "ARTIFACT_INVALID"
    elif reason in _CONTENT_REVIEW_REASONS:
        return "CONTENT_REVIEW_REQUIRED"
    else:
        return "INTERNAL_FAILURE"


def formal_reason_codes(reasons: list[str]) -> list[str]:
    return sorted({formal_reason_code(reason) for reason in reasons})


def reason_codes_are_valid(value: Any, *, formal: bool) -> bool:
    allowed = FORMAL_REASON_CODES if formal else _DETAILED_REASON_CODES
    return (
        isinstance(value, list)
        and bool(value)
        and all(isinstance(reason, str) and reason in allowed for reason in value)
        and len(value) == len(set(value))
    )
