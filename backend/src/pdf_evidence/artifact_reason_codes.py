_SOURCE_INVALID_REASONS = {
    "MEDIA_TYPE_INVALID",
    "PDF_INVALID",
    "PAGE_SELECTION_INVALID",
}
_RESOURCE_LIMIT_REASONS = {"PROTOCOL_LIMIT_EXCEEDED", "MODEL_INPUT_TOO_LARGE"}
_PROCESS_FAILED_REASONS = {
    "CHILD_EXITED",
    "CHILD_RESPONSE_INVALID",
    "CONCEPT_API_RESPONSE_INVALID",
    "CONCEPT_API_UNAVAILABLE",
    "MODEL_OOM",
    "MODEL_GENERATION_FAILED",
}
